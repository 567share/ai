export const detectSystemLanguage = (): Language => {
  if (typeof window === 'undefined' || !navigator) return 'en';
  const lang = navigator.language || (navigator as any).userLanguage || 'en';
  const shortLang = lang.toLowerCase().slice(0, 2);

  switch (shortLang) {
    case 'zh': return 'zh';
    case 'es': return 'es';
    case 'ja': return 'ja';
    case 'de': return 'de';
    case 'fr': return 'fr';
    case 'pt': return 'pt';
    case 'ko': return 'ko';
    default: return 'en';
  }
};

